#!/usr/bin/env python3
"""Демо 5, «Пять агентов» (цикл 4 семинара «Цена ошибки AI-агента»).

Четыре независимых агента (разные модели) отвечают на тот же вопрос того же
договора, что в демо 1 и демо 4. Суммы читаются глазами из заголовков ответов —
автопарсинга нет по принципу: ошибка извлечения дороже отсутствия таблицы.

Проверенный замер (15.10, temp 0, стабилен на повторных прогонах):
  llama3.2:1b   — числа нет вовсе, ссылка на п. 4.3;
  qwen3:4b      — 240 000 ₽ (ошибка демо 1 воспроизводится);
  qwen3.5:9b    — поправил себя по ходу, сошёлся на 48 000 ₽ («20 рабочих дней»);
  gemma4:12b    — в заголовке 140 000 ₽, в расчёте 48 000 ₽, в примечании 144 000 ₽.
Эталон 52 800 ₽ не набирает ни одного голоса. Двое, сошедшиеся на 48 000 ₽,
сошлись на неверном числе по одной причине — неверный рабочий календарь.

Ход прогона: вопрос, четыре сырых ответа подряд, пауза на Enter,
строка голосования и вердикт.

После ответа каждой модели скрипт молча сверяет её заголовочное число с
проверенным замером: если ответ уплыл, в конце печатается предупреждение
о дрейфе от проверенного замера — это сигнал дрейфа, а не таблица сумм.
"""

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "shared"))
from run_agent import ask_ollama, load_shared, build_agent_prompt  # noqa: E402

BAR = "=" * 64

# Порядок — сценарный: сначала отказ без числа, затем знакомая ошибка демо 1,
# затем «умный, который себя поправил», затем ответ с внутренним противоречием.
FLEET = [
    ("llama3.2:1b", "АГЕНТ 1"),
    ("qwen3:4b-instruct-2507-q4_K_M", "АГЕНТ 2"),
    ("qwen3.5:9b", "АГЕНТ 3"),
    ("gemma4:12b", "АГЕНТ 4"),
]

# Ожидаемое заголовочное число из проверенного замера (None — числа в ответе нет).
# Используется только для сигнала дрейфа, на экран суммы не извлекаются.
EXPECTED = {
    "llama3.2:1b": None,
    "qwen3:4b-instruct-2507-q4_K_M": "240 000",
    "qwen3.5:9b": "48 000",
    "gemma4:12b": "140 000",
}


def drifted(model, answer):
    """True, если ответ модели отличается от проверенного замера 15.10."""
    expected = EXPECTED[model]
    if expected is None:
        # ожидаем отсутствие итоговой суммы: дрейф — если сумма вдруг появилась
        return "52 800" in answer or "240 000" in answer or "48 000" in answer
    compact = expected.replace(" ", "")
    return expected not in answer and compact not in answer


def main():
    contract, etalon = load_shared()
    prompt = build_agent_prompt(contract, etalon["question"])

    print(BAR)
    print("ДЕМО 5. ПЯТЬ АГЕНТОВ: А ЕСЛИ ВМЕСТО ВЕРИФИКАТОРА — ЕЩЁ АГЕНТОВ?")
    print("Четыре независимых агента | temperature 0 | офлайн | последовательно")
    print(BAR)
    print()
    print("ДОКУМЕНТ: Договор поставки № 17-Т/2026 (тот же, что в демо 1 и 4)")
    print()
    print("ВОПРОС КАЖДОМУ (тот же):")
    print(" ", etalon["question"])
    print()

    drift_alerts = []
    for model, label in FLEET:
        print(BAR)
        print(f"{label} — модель {model}")
        print(BAR)
        t0 = time.time()
        try:
            answer = ask_ollama(prompt, model=model, stream=True, timeout=600, num_predict=900)
        except Exception as e:  # noqa: BLE001
            answer = ""
            print(f"[ОШИБКА ЗАПУСКА: {type(e).__name__}: {e}]")
        dt = time.time() - t0
        print()
        print(f"--- {label} закончил за {dt:.0f} с ---")
        print()
        if answer and drifted(model, answer):
            drift_alerts.append(model)

    print(BAR)
    input("Нажмите Enter — итог голосования...")
    print()

    print(BAR)
    print("ГОЛОСОВАНИЕ (заголовки на экране выше, подсчёт — глазами):")
    print(BAR)
    print()
    print("  Агент 1 (llama3.2:1b):  числа нет вовсе — процитировал договор,")
    print("                          сослался на п. 4.3. Воздержался.")
    print("  Агент 2 (qwen3:4b):     240 000 ₽ — знакомое число: это ровно")
    print("                          ошибка первого цикла, она воспроизвелась.")
    print("  Агент 3 (qwen3.5:9b):   48 000 ₽ — по ходу сам себя поправил,")
    print("                          пересчитал рабочие дни и сошёлся на 20.")
    print("  Агент 4 (gemma4:12b):   140 000 ₽ в заголовке — и два других числа")
    print("                          (48 000 и 144 000) в том же ответе.")
    print()
    etalon_rub = f"{etalon['correct']['answer_rub']:,}".replace(",", " ")
    print(f"  ЭТАЛОН: {etalon_rub} ₽ (п. 4.1, 22 рабочих дня).")
    print("  СОВПАДЕНИЙ С ЭТАЛОНОМ: НИ ОДНОГО.")
    print()
    print("  Вердикт: голосование не состоялось — голосовать было не за что.")
    print("  Все четыре ошиблись, и ошиблись одинаково: на рабочем календаре.")
    print("  Голосование гасит НЕЗАВИСИМЫЕ ошибки агентов, которые ЧАЩЕ ПРАВЫ.")
    print("  Общую системную ошибку оно только подтверждает — четырежды.")
    print()

    if drift_alerts:
        print(BAR)
        print("ВНИМАНИЕ: ответ дрейфует от проверенного замера 15.10 у:", ", ".join(drift_alerts))
        print("  Строка голосования выше — из проверенного замера.")
        print("  Эталонный вывод этого же прогона: fallback/demo5_transcript.txt")
        print(BAR)
        print()


if __name__ == "__main__":
    main()
