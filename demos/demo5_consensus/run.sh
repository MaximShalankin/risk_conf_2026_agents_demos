#!/bin/zsh
# Демо 5 «Пять агентов» — запуск одной командой
cd "$(dirname "$0")"
# Прогрев всех четырёх моделей: холодная загрузка съедает секунды прогона.
# Если все четыре в память не помещаются, ollama выгрузит лишние — это нормально,
# загрузка добавит каждому агенту несколько секунд, но не сломает прогон.
for m in llama3.2:1b qwen3:4b-instruct-2507-q4_K_M qwen3.5:9b gemma4:12b; do
  curl -s http://localhost:11434/api/generate -d "{\"model\":\"$m\",\"keep_alive\":\"15m\"}" > /dev/null
done
python3 demo5.py
